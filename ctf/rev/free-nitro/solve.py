#!/usr/bin/env python3
from Crypto.Cipher import AES

MSA = 0x02221736F0F06707
MSB = 0x31CBA7E18134D926
SCH_A = 0x9E3779B97F4A7C15
SCH_B = 0xB7E151628AED2A6B
MASK = (1 << 64) - 1

def mix64(x):
    x = (x + 0x9E3779B97F4A7C15) & MASK
    x = ((x ^ (x >> 30)) * 0xBF58476D1CE4E5B9) & MASK
    x = ((x ^ (x >> 27)) * 0x94D049BB133111EB) & MASK
    return x ^ (x >> 31)

NONCE = bytes([0x1A, 0xD0, 0x0F, 0xFE, 0x42, 0x9B, 0xE5, 0x77, 0x0C, 0x90, 0xA6, 0x33])
AES_CT = bytes([
    0x23, 0x70, 0x57, 0xAA, 0x8A, 0x59, 0x9F, 0x98, 0x5A, 0xDE, 0x19, 0x70,
    0x74, 0xE3, 0x34, 0x14, 0xE1, 0x58, 0xA4, 0x85, 0x71, 0xBE, 0x02, 0x37,
    0x04, 0x5C, 0x56, 0x88, 0xC3, 0x8F, 0x67, 0x59, 0x41, 0x5A, 0xFB, 0x90,
    0x2F, 0xA6, 0xB1, 0x27, 0xBB, 0x9E, 0xD6, 0x64, 0xF3, 0x24, 0xC9, 0xA6,
    0x77, 0xAE, 0x72, 0xBB, 0x46, 0x2E, 0x11, 0x1B, 0xFA, 0xDF, 0xC3, 0xE8,
    0xE7, 0x50, 0xB9, 0x69
])
AES_TAG = bytes([
    0x82, 0x8F, 0xB7, 0xA8, 0x60, 0xB1, 0x3B, 0x54, 0xD8, 0xE7, 0x1D, 0x72,
    0x7D, 0xB2, 0x14, 0x1F
])

def aes_key_bytes(msa, msb):
    x = (mix64(msa ^ msb) ^ SCH_B) ^ SCH_A
    out = bytearray()
    for _ in range(4):
        x = mix64(x) & MASK
        out += x.to_bytes(8, "little")
    return bytes(out)

key = aes_key_bytes(MSA, MSB)

print(AES.new(key, AES.MODE_GCM, nonce=NONCE).decrypt_and_verify(AES_CT, AES_TAG).decode())